-- ANALYTICS FACT TABLES
CREATE TABLE IF NOT EXISTS analytics.fact_orders (
 order_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id TEXT UNIQUE, customer_sk BIGINT,
 purchase_date_sk INTEGER, approval_date_sk INTEGER,
 carrier_date_sk INTEGER, delivery_date_sk INTEGER,
 estimated_delivery_date_sk INTEGER,
 order_status TEXT, is_delivered BOOLEAN, is_on_time BOOLEAN,
 delivery_days NUMERIC(12,4), delivery_delay_days NUMERIC(12,4)
);
CREATE TABLE IF NOT EXISTS analytics.fact_order_items (
 order_item_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_sk BIGINT, order_id TEXT, order_item_id INTEGER,
 product_sk BIGINT, seller_sk BIGINT, shipping_date_sk INTEGER,
 price NUMERIC(12,2), freight_value NUMERIC(12,2),
 item_total_value NUMERIC(12,2)
);
CREATE TABLE IF NOT EXISTS analytics.fact_payments (
 payment_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_sk BIGINT, order_id TEXT, payment_type_sk INTEGER,
 payment_sequential INTEGER, payment_installments INTEGER,
 payment_value NUMERIC(12,2)
);
CREATE TABLE IF NOT EXISTS analytics.fact_reviews (
 review_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_sk BIGINT, order_id TEXT, review_date_sk INTEGER,
 review_answer_date_sk INTEGER, review_id TEXT,
 review_score SMALLINT, review_comment_title TEXT,
 review_comment_message TEXT
);

-- Full refresh population. Run after dimensions are populated.
TRUNCATE TABLE analytics.fact_orders RESTART IDENTITY CASCADE;
INSERT INTO analytics.fact_orders(
 order_id,customer_sk,purchase_date_sk,approval_date_sk,carrier_date_sk,
 delivery_date_sk,estimated_delivery_date_sk,order_status,is_delivered,
 is_on_time,delivery_days,delivery_delay_days)
SELECT o.order_id,c.customer_sk,
 TO_CHAR(o.order_purchase_timestamp::date,'YYYYMMDD')::integer,
 TO_CHAR(o.order_approved_at::date,'YYYYMMDD')::integer,
 TO_CHAR(o.order_delivered_carrier_date::date,'YYYYMMDD')::integer,
 TO_CHAR(o.order_delivered_customer_date::date,'YYYYMMDD')::integer,
 TO_CHAR(o.order_estimated_delivery_date::date,'YYYYMMDD')::integer,
 o.order_status,o.is_delivered,o.is_on_time,o.delivery_days,o.delivery_delay_days
FROM staging.stg_orders o
LEFT JOIN analytics.dim_customers c ON c.customer_id=o.customer_id;

TRUNCATE TABLE analytics.fact_order_items RESTART IDENTITY CASCADE;
INSERT INTO analytics.fact_order_items(
 order_sk,order_id,order_item_id,product_sk,seller_sk,shipping_date_sk,
 price,freight_value,item_total_value)
SELECT fo.order_sk,i.order_id,i.order_item_id,p.product_sk,s.seller_sk,
 TO_CHAR(i.shipping_limit_date::date,'YYYYMMDD')::integer,
 i.price,i.freight_value,i.item_total_value
FROM staging.stg_order_items i
LEFT JOIN analytics.fact_orders fo ON fo.order_id=i.order_id
LEFT JOIN analytics.dim_products p ON p.product_id=i.product_id
LEFT JOIN analytics.dim_sellers s ON s.seller_id=i.seller_id;

TRUNCATE TABLE analytics.fact_payments RESTART IDENTITY CASCADE;
INSERT INTO analytics.fact_payments(
 order_sk,order_id,payment_type_sk,payment_sequential,payment_installments,payment_value)
SELECT fo.order_sk,p.order_id,pt.payment_type_sk,p.payment_sequential,
 p.payment_installments,p.payment_value
FROM staging.stg_order_payments p
LEFT JOIN analytics.fact_orders fo ON fo.order_id=p.order_id
LEFT JOIN analytics.dim_payment_type pt ON pt.payment_type=p.payment_type;

TRUNCATE TABLE analytics.fact_reviews RESTART IDENTITY CASCADE;
INSERT INTO analytics.fact_reviews(
 order_sk,order_id,review_date_sk,review_answer_date_sk,review_id,
 review_score,review_comment_title,review_comment_message)
SELECT fo.order_sk,r.order_id,
 TO_CHAR(r.review_creation_date::date,'YYYYMMDD')::integer,
 TO_CHAR(r.review_answer_timestamp::date,'YYYYMMDD')::integer,
 r.review_id,r.review_score,r.review_comment_title,r.review_comment_message
FROM staging.stg_order_reviews r
LEFT JOIN analytics.fact_orders fo ON fo.order_id=r.order_id;
