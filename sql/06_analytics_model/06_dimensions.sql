-- ANALYTICS DIMENSIONS
CREATE TABLE IF NOT EXISTS analytics.dim_customers (
 customer_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id TEXT UNIQUE, customer_unique_id TEXT,
 zip_code_prefix VARCHAR(5), city TEXT, state CHAR(2), geography_sk BIGINT
);
CREATE TABLE IF NOT EXISTS analytics.dim_products (
 product_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id TEXT UNIQUE, product_category_name TEXT,
 product_category_english TEXT, product_name_lenght INTEGER,
 product_description_lenght INTEGER, product_photos_qty INTEGER,
 product_weight_g NUMERIC(12,3), product_length_cm NUMERIC(12,3),
 product_height_cm NUMERIC(12,3), product_width_cm NUMERIC(12,3)
);
CREATE TABLE IF NOT EXISTS analytics.dim_sellers (
 seller_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 seller_id TEXT UNIQUE, zip_code_prefix VARCHAR(5), city TEXT,
 state CHAR(2), geography_sk BIGINT
);
CREATE TABLE IF NOT EXISTS analytics.dim_geography (
 geography_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 zip_code_prefix VARCHAR(5), city TEXT, state CHAR(2),
 latitude NUMERIC(12,8), longitude NUMERIC(12,8)
);
CREATE TABLE IF NOT EXISTS analytics.dim_date (
 date_sk INTEGER PRIMARY KEY, full_date DATE UNIQUE,
 day_of_month SMALLINT, day_of_week SMALLINT, day_name TEXT,
 week_of_year SMALLINT, month_number SMALLINT, month_name TEXT,
 quarter_number SMALLINT, year_number SMALLINT,
 is_weekend BOOLEAN, is_month_start BOOLEAN, is_month_end BOOLEAN
);
CREATE TABLE IF NOT EXISTS analytics.dim_payment_type (
 payment_type_sk INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payment_type TEXT UNIQUE
);

-- Populate geography using deduplicated ZIP representative coordinates.
TRUNCATE TABLE analytics.dim_geography RESTART IDENTITY CASCADE;
INSERT INTO analytics.dim_geography(zip_code_prefix,city,state,latitude,longitude)
SELECT zip_code_prefix, city, state, latitude, longitude
FROM staging.stg_geography_zip;

-- Customer and seller geography are joined through ZIP prefix.
TRUNCATE TABLE analytics.dim_customers RESTART IDENTITY CASCADE;
INSERT INTO analytics.dim_customers(customer_id,customer_unique_id,zip_code_prefix,city,state,geography_sk)
SELECT c.customer_id,c.customer_unique_id,c.customer_zip_code_prefix,c.customer_city,c.customer_state,g.geography_sk
FROM staging.stg_customers c
LEFT JOIN LATERAL (
 SELECT geography_sk FROM analytics.dim_geography
 WHERE zip_code_prefix=c.customer_zip_code_prefix
 ORDER BY geography_sk LIMIT 1
) g ON TRUE;

TRUNCATE TABLE analytics.dim_products RESTART IDENTITY CASCADE;
INSERT INTO analytics.dim_products(product_id,product_category_name,product_category_english,
 product_name_lenght,product_description_lenght,product_photos_qty,
 product_weight_g,product_length_cm,product_height_cm,product_width_cm)
SELECT product_id,product_category_name,product_category_english,
 product_name_lenght,product_description_lenght,product_photos_qty,
 product_weight_g,product_length_cm,product_height_cm,product_width_cm
FROM staging.stg_products;

TRUNCATE TABLE analytics.dim_sellers RESTART IDENTITY CASCADE;
INSERT INTO analytics.dim_sellers(seller_id,zip_code_prefix,city,state,geography_sk)
SELECT s.seller_id,s.seller_zip_code_prefix,s.seller_city,s.state,g.geography_sk
FROM staging.stg_sellers s
LEFT JOIN LATERAL (
 SELECT geography_sk FROM analytics.dim_geography
 WHERE zip_code_prefix=s.seller_zip_code_prefix
 ORDER BY geography_sk LIMIT 1
) g ON TRUE;

TRUNCATE TABLE analytics.dim_payment_type RESTART IDENTITY CASCADE;
INSERT INTO analytics.dim_payment_type(payment_type)
SELECT DISTINCT payment_type FROM staging.stg_order_payments
ORDER BY payment_type;

-- Date dimension spans all source lifecycle dates and review dates.
TRUNCATE TABLE analytics.dim_date;
INSERT INTO analytics.dim_date
SELECT TO_CHAR(d::date,'YYYYMMDD')::integer, d::date,
 EXTRACT(DAY FROM d)::smallint,
 EXTRACT(ISODOW FROM d)::smallint,
 TRIM(TO_CHAR(d,'Day')),
 EXTRACT(WEEK FROM d)::smallint,
 EXTRACT(MONTH FROM d)::smallint,
 TRIM(TO_CHAR(d,'Month')),
 EXTRACT(QUARTER FROM d)::smallint,
 EXTRACT(YEAR FROM d)::smallint,
 EXTRACT(ISODOW FROM d) IN (6,7),
 d::date=DATE_TRUNC('month',d)::date,
 d::date=(DATE_TRUNC('month',d)+INTERVAL '1 month - 1 day')::date
FROM generate_series(
 (SELECT LEAST(
   (SELECT MIN(order_purchase_timestamp)::date FROM raw.olist_orders),
   (SELECT MIN(review_creation_date)::date FROM raw.olist_order_reviews)
 )),
 (SELECT GREATEST(
   (SELECT MAX(order_estimated_delivery_date)::date FROM raw.olist_orders),
   (SELECT MAX(review_creation_date)::date FROM raw.olist_order_reviews)
 )), INTERVAL '1 day'
) g(d);
